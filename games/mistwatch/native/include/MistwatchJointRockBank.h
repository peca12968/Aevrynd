struct Receipt {std::size_t changed{};float maximumRise{};};
inline Receipt Apply(ValleyTerrain::Result& result,std::span<const Aevrynd::BoxCollider3D> pads){
    if(WestCliffRelief::Fingerprint(result.terrain)!=16546567984029864090ull)
        throw std::invalid_argument("JOINT_BANK_INPUT_TERRAIN");
    const auto old=result.terrain;Receipt receipt{};float actualMaximum=old.MaximumHeight();
    for(unsigned z=0;z<old.Settings().depth;++z)for(unsigned x=0;x<old.Settings().width;++x){
        const auto p=old.SamplePosition(x,z);float rise{};
        if(p.x< -47.5f||p.x> -25.5f||p.z<53||p.z>74)continue;
        for(const auto& s:Seeds){const float t=std::clamp(1.f-std::hypot(p.x-s.x,p.z-s.z)/3.f,0.f,1.f);
            rise=(std::max)(rise,s.rise*t*t*(3-2*t));}
        if(rise<=1.e-6f)continue;
        const float half=old.Settings().cellSize;
        WestCliffRelief::ValidateProtectedRectangle(p.x-half,p.x+half,p.z-half,p.z+half);
        for(const auto& b:pads)if(p.x+half>b.center.x-b.extents.x&&p.x-half<b.center.x+b.extents.x&&
            p.z+half>b.center.z-b.extents.z&&p.z-half<b.center.z+b.extents.z)
            throw std::invalid_argument("JOINT_BANK_EXISTING_HARD_SUPPORT");
        if(!std::isfinite(rise)||rise>3.f)throw std::invalid_argument("JOINT_BANK_HEIGHT_RANGE");
        result.terrain.SetHeight(x,z,p.y+rise);actualMaximum=(std::max)(actualMaximum,p.y+rise);
        ++receipt.changed;receipt.maximumRise=(std::max)(receipt.maximumRise,rise);
    }
    result.terrain.RecalculateRange();
    if(!receipt.changed||!WestCliffRelief::Bits(old.MinimumHeight(),result.terrain.MinimumHeight())||
        !WestCliffRelief::Bits(actualMaximum,result.terrain.MaximumHeight()))
        throw std::invalid_argument("JOINT_BANK_WORLD_EXTREMA");
    result.changed+=receipt.changed;return receipt;
}
